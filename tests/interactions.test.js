/** @vitest-environment jsdom */
import { expect, it, vi } from 'vitest';
vi.mock('../src/map.js', async importOriginal => {
 const actual = await importOriginal();
 return {...actual,mountTripMap:vi.fn(({onPlaybackState=()=>{}})=>({play:vi.fn(()=>{onPlaybackState(true);return Promise.resolve();}),stop:vi.fn(()=>onPlaybackState(false)),destroy:vi.fn(),focus:vi.fn(),overview:vi.fn()}))};
});

it('keeps guide, next stop, completion filtering and slideshow controls usable across redraws', async () => {
  vi.useFakeTimers();
  window.matchMedia = vi.fn(() => ({ matches: false }));
  window.scrollTo = vi.fn();
  const scroll = vi.fn();
  Element.prototype.scrollIntoView = scroll;
  window.requestAnimationFrame = (callback) => callback();
  localStorage.clear();
  document.body.innerHTML = '<div id="app"></div>';
  vi.stubGlobal('fetch', vi.fn(async () => ({ ok: false })));
  vi.stubGlobal('ResizeObserver', class { observe() {} disconnect() {} });
  HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  HTMLDialogElement.prototype.close = function () { this.dispatchEvent(new Event('close')); };
  await import('../src/main.js');
  // A compact itinerary retains every full guide behind native disclosures.
  expect([...document.querySelectorAll('.stop-detail')].every(detail => !detail.open)).toBe(true);
  document.querySelector('[data-schedule-mode="detail"]').click();
  expect([...document.querySelectorAll('.stop-detail')].every(detail => detail.open)).toBe(true);
  document.querySelector('[data-day="1"]').click();
  expect([...document.querySelectorAll('.stop-detail')].every(detail => detail.open)).toBe(true);
  document.querySelector('[data-schedule-mode="summary"]').click();
  expect([...document.querySelectorAll('.stop-detail')].every(detail => !detail.open)).toBe(true);
  document.querySelector('[data-day="0"]').click();
  document.querySelector('.stop-detail').open = true;
  const airportMap = document.querySelector('[data-transit-map-open="airport"]');
  airportMap.click();
  expect(document.querySelector('dialog h2').textContent).toContain('간사이공항');
  document.querySelector('[data-castle-close]').click();
  expect(document.activeElement).toBe(airportMap);

  const originalTip = document.querySelector('[data-guide-message]').textContent;
  document.querySelector('.tip-cycle').click();
  expect(document.querySelector('[data-guide-message]').textContent).not.toBe(originalTip);
  expect(document.querySelector('[data-tip-count]').textContent).toBe('2 / 3');

  document.querySelector('.trip-details').open = true;
  const first = document.querySelector('[data-stop-id]');
  const id = first.dataset.stopId;
  first.click();
  expect(document.querySelector(`[data-stop-id="${id}"]`).getAttribute('aria-pressed')).toBe('true');
  expect(document.querySelector('.trip-details').open).toBe(true);
  expect(document.querySelector('.stop-detail').open).toBe(true);
  expect(document.querySelector('.travel-toast[role="status"]').textContent).toContain('완료했어요');
  expect(JSON.parse(localStorage.getItem('osaka-kyoto-family-trip-v1')).completedStops).toContain(id);
  document.querySelector('[data-hide-completed]').click();
  expect(document.querySelector('.timeline').classList.contains('hide-completed')).toBe(true);
  document.querySelector('[data-next-stop]').click();
  expect(scroll).toHaveBeenCalled();
  expect(document.activeElement.dataset.stopId).not.toBe(id);

  const counter = document.querySelector('[data-hero-counter]').textContent;
  vi.advanceTimersByTime(10000);
  expect(document.querySelector('[data-hero-counter]').textContent).toBe(counter);
  document.querySelector('[data-hero-next]').click();
  expect(document.querySelector('[data-hero-counter]').textContent).not.toBe(counter);
  document.querySelector('[data-day="1"]').click();
  const jrMap = document.querySelector('[data-transit-map-open="jr"]');
  jrMap.click();
  expect(document.querySelector('dialog h2').textContent).toContain('JR 신쾌속');
  document.querySelector('[data-castle-close]').click();
  expect(document.activeElement).toBe(jrMap);
  expect(document.querySelector('[data-hide-completed]').getAttribute('aria-pressed')).toBe('true');
  expect(document.querySelector('[data-hero-pause]')).toBeNull();
  expect(document.querySelector('[data-tip-count]').textContent).toBe('1 / 3');
  const destination = document.querySelector('[data-scroll-stop]');
  const destinationId = destination.dataset.scrollStop;
  document.querySelector(`[data-stop-id="${destinationId}"]`).click();
  document.querySelector('[data-scroll-stop]').click();
  expect(document.querySelector('.timeline').classList.contains('hide-completed')).toBe(false);
  expect(document.activeElement.dataset.stopId).toBe(destinationId);

  const placeGuideButton = document.querySelector('[data-open-guide]');
  const guideStopId = placeGuideButton.dataset.scrollStop;
  // A guide must also remain reachable when its completed stop is filtered out.
  if (document.querySelector(`[data-stop-id="${guideStopId}"]`).getAttribute('aria-pressed') !== 'true') {
    document.querySelector(`[data-stop-id="${guideStopId}"]`).click();
  }
  document.querySelector('[data-hide-completed]').click();
  document.querySelector(`[data-open-guide][data-scroll-stop="${guideStopId}"]`).click();
  const placeGuide = document.querySelector(`#guide-${guideStopId}`);
  expect(placeGuide.open).toBe(true);
  expect(placeGuide.closest('.stop-detail').open).toBe(true);
  expect(document.activeElement).toBe(placeGuide.querySelector('summary'));
  expect(document.querySelector('.timeline').classList.contains('hide-completed')).toBe(false);
  expect(document.querySelector(`[data-stop-id="${guideStopId}"]`).getAttribute('aria-pressed')).toBe('true');

  document.querySelector('.trip-menu [data-view="food"]').click();
  expect(document.querySelector('#itinerary').hidden).toBe(true);
  expect(document.querySelector('.dining-view').hidden).toBe(false);
  expect(document.activeElement.id).toBe('dining-title');
  expect(window.location.hash).toBe('#restaurants');
  expect(document.querySelectorAll('.dining-card')).toHaveLength(4);
  expect(document.querySelector('.dining-map[href*="WyCUtCna6JTLZKka7"]')).not.toBeNull();
  document.querySelector('.trip-menu [data-view="shopping"]').click();
  expect(document.querySelector('#itinerary').hidden).toBe(true);
  expect(document.querySelector('.trip-overview').hidden).toBe(true);
  expect(document.querySelector('.dining-view').hidden).toBe(true);
  expect(document.querySelector('.shopping-view').hidden).toBe(false);
  expect(document.activeElement.id).toBe('shopping-title');
  expect(window.location.hash).toBe('#shopping');
  expect(document.querySelector('.trip-menu [data-view="shopping"]').getAttribute('aria-current')).toBe('page');
  expect(document.querySelectorAll('.shopping-card')).toHaveLength(6);
  const convenienceStore = document.querySelector('#shop-daily-yamazaki-kyoto');
  expect(convenienceStore.textContent).toContain('교토역 데일리 야마자키');
  expect(convenienceStore.querySelector('iframe').src).toContain('youtube.com/embed/nPz4Hw9r-E8?playsinline=1');
  expect(document.querySelector('.shopping-view').textContent).toContain('스탠다드 프로덕츠');
  expect(document.querySelector('.shopping-card .dining-map').href).toContain('google.com/maps/search/');
  document.querySelector('.shopping-view .dining-return').click();
  expect(document.querySelector('.shopping-view').hidden).toBe(true);
  expect(document.querySelector('[data-day="1"]').getAttribute('aria-current')).toBe('date');
  expect(document.querySelector(`[data-stop-id="${destinationId}"]`).getAttribute('aria-pressed')).toBe('true');
  document.querySelector('.trip-menu [data-view="food"]').click();
  document.querySelector('.dining-return').click();
  expect(document.querySelector('#itinerary').hidden).toBe(false);
  expect(document.querySelector('.dining-view').hidden).toBe(true);
  expect(document.querySelector('[data-day="1"]').getAttribute('aria-current')).toBe('date');
  expect(document.querySelector(`[data-stop-id="${destinationId}"]`).getAttribute('aria-pressed')).toBe('true');
  window.history.replaceState(null, '', '#restaurants');
  window.dispatchEvent(new PopStateEvent('popstate'));
  expect(document.querySelector('.dining-view').hidden).toBe(false);
  window.history.replaceState(null, '', '#shopping');
  window.dispatchEvent(new PopStateEvent('popstate'));
  expect(document.querySelector('.shopping-view').hidden).toBe(false);
  expect(document.querySelector('.dining-view').hidden).toBe(true);
  window.history.replaceState(null, '', '#itinerary');
  window.dispatchEvent(new PopStateEvent('popstate'));
  expect(document.querySelector('#itinerary').hidden).toBe(false);

  document.querySelector('.trip-menu [data-view="preparation"]').click();
  expect(document.querySelector('.preparation-view').hidden).toBe(false);
  expect(document.activeElement.id).toBe('preparation-title');
  expect(window.location.hash).toBe('#preparation');
  const passport = document.querySelector('[data-preparation-id="passports"]');
  passport.focus();
  passport.click();
  expect(document.querySelector('[data-prep-progress]').value).toBe(1);
  expect(document.activeElement).toBe(passport);
  expect(JSON.parse(localStorage.getItem('osaka-kyoto-family-trip-v1')).completedPreparation).toEqual(['passports']);
  document.querySelector('.trip-menu [data-view="shopping"]').click();
  document.querySelector('.trip-menu [data-view="preparation"]').click();
  expect(document.querySelector('[data-preparation-id="passports"]').checked).toBe(true);
  document.querySelector('[data-preparation-id="passports"]').click();
  expect(document.querySelector('[data-prep-progress]').value).toBe(0);
  document.querySelector('.preparation-view .dining-return').click();
  document.querySelector('[data-day="3"]').click();
  const harukaMap = document.querySelector('[data-transit-map-open="haruka"]');
  harukaMap.click();
  expect(document.querySelector('dialog h2').textContent).toContain('하루카');
  expect(document.querySelector('dialog svg').getAttribute('viewBox')).toBe('0 0 1440 2020');
  expect(document.querySelector('dialog image').getAttribute('href')).toBe('/images/guides/kyoto-station-full.png');
  document.querySelector('[data-castle-close]').click();
  expect(document.activeElement).toBe(harukaMap);
  document.querySelector('[data-view="itinerary"]').click();
  expect(document.querySelector('#day-route-map')).not.toBeNull();
  const replay = document.querySelector('[data-inline-map-play]');
  replay.click();
  expect(replay.getAttribute('aria-pressed')).toBe('true');
  replay.click();
  expect(replay.getAttribute('aria-pressed')).toBe('false');
  const install = document.querySelector('footer .install-button');
  install.click();
  expect(document.querySelector('main').inert).toBe(true);
  expect(document.activeElement.classList.contains('install-close')).toBe(true);
  document.querySelector('.install-close').click();
  expect(document.querySelector('main').inert).toBe(false);
  expect(document.activeElement).toBe(document.querySelector('footer .install-button'));
  vi.clearAllTimers();
  vi.useRealTimers();
  vi.unstubAllGlobals();
}, 120000);
